        <h1>Studenti</h1>
        <h2>Come posso registrarmi sulla piattaforma?</h2>
        <p>Accedi alla home page del sito, seleziona "Login o Registrati" e seleziona la voce "Studente”. Compila tutti
            i campi richiesti e conferma l’iscrizione. Riceverai un’email di conferma all’indirizzo indicato. Ricorda
            che sono accettate esclusivamente email istituzionali.</p>
        <h2>Posso modificare il mio profilo dopo la registrazione?</h2>
        <p>Sì, puoi accedere in qualsiasi momento alla sezione “Profilo” in alto a destra per aggiornare il profilo.</p>
        <h2>Come funziona la prenotazione del colloquio tramite QR-code?</h2>
        <p>Durante la giornata del Career Day, ogni azienda disporrà di un QR-code identificativo. Ti basterà inquadrare
            il codice con il tuo smartphone o dispositivo per accedere alla pagina di prenotazione e confermare il
            colloquio.</p>
        <h2>Cosa succede dopo aver prenotato un colloquio?</h2>
        <p>L’azienda riceverà la tua prenotazione e potrà consultare il tuo profilo. Dopo l’incontro, l’azienda potrà
            lasciare un feedback o una valutazione sulla tua presentazione.</p>
        <h2>Non riesco ad accedere al mio account. Cosa devo fare?</h2>
        <p>Clicca su “Password dimenticata?” nella pagina di login. Inserisci la tua email e segui le istruzioni per
            reimpostare la password. In alternativa puoi contattare un amministratore per richiedere il reset della
            password.</p>
    </div>

    <div class="faq-container">
        <h1>Aziende</h1>
        <h2>Come posso aderire al Career Day?</h2>
        <p>Registrati come azienda sul portale compilando i campi richiesti e attendi che la scuola approvi la tua
            adesione. Successivamente potrai vedere l'evento sulla piattaforma. </p>
        <h2>Posso modificare o aggiornare le posizioni aperte?</h2>
        <p>Sì. Accedi con le tue credenziali e vai nella sezione “Posizioni. Da lì puoi aggiungere, modificare o
            eliminare le posizioni lavorative proposte.</p>
        <h2>Come visualizzo le prenotazioni degli studenti?</h2>
        <p>Nel pannello aziendale è disponibile la sezione "Colloqui", dove puoi visualizzare l’elenco degli studenti
            che hanno prenotato un colloquio con la tua azienda durante il Career Day.</p>
        <h2>Posso accedere ai profili di tutti gli studenti registrati?</h2>
        <p>No. Per motivi di privacy, puoi visualizzare soltanto i profili degli studenti che hanno prenotato un
            colloquio con la tua azienda.</p>
        <h2>Come posso lasciare un feedback sull’evento?</h2>
        <p>Dopo il Career Day, accedi alla sezione “Feedback” nel footer del tuo account aziendale e compila il
            questionario di gradimento. Il tuo contributo aiuterà a migliorare l’organizzazione dei prossimi eventi.</p>
        <h2>Non riesco ad accedere al mio account. Cosa devo fare?</h2>
        <p>Clicca su “Password dimenticata?” nella pagina di login. Inserisci la tua email e segui le istruzioni per
            reimpostare la password. In alternativa puoi contattare un amministratore per richiedere il reset della
            password.</p>
